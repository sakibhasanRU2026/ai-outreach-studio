function hoursAgo(hours: number): string {
  return new Date(Date.now() - hours * 3600 * 1000).toISOString();
}

function buildAnalyticsSeries(): AnalyticsDayPoint[] {
  const points: AnalyticsDayPoint[] = [];
  const today = new Date();
  for (let i = 89; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(today.getDate() - i);
    const wave = Math.sin(i * 0.35) * 4 + Math.cos(i * 0.15) * 3;
    const baseLeads = Math.max(8, Math.round(18 + wave + (i % 5)));
    const sent = Math.max(5, Math.round(baseLeads * 0.82));
    const accepted = Math.max(2, Math.round(sent * 0.44));
    const replies = Math.max(1, Math.round(accepted * 0.36));
    const positive = Math.max(0, Math.round(replies * 0.58));
    const failed = i % 9 === 0 ? 2 : i % 4 === 0 ? 1 : 0;
    points.push({
      date: d.toISOString().slice(0, 10),
      leadsProcessed: baseLeads,
      connectionsSent: sent,
      connectionsAccepted: accepted,
      repliesReceived: replies,
      positiveReplies: positive,
      failedExecutions: failed,
    });
  }
  return points;
}

